import React, { useState } from 'react';
import { motion } from 'framer-motion';
import {
  Lightbulb,
  CheckCircle2,
  Circle,
  Droplets,
  Sprout,
  SunMedium,
  FlaskConical,
  Info,
  Calendar,
  ArrowRight,
  ShieldAlert,
  Sparkles
} from 'lucide-react';
import { useFarm } from '../../context/FarmContext';

export default function RecommendationsView() {
  const { recommendations, setActiveTab } = useFarm();
  const [completedMap, setCompletedMap] = useState({});

  const toggleTask = (id) => {
    setCompletedMap((prev) => ({ ...prev, [id]: !prev[id] }));
  };

  return (
    <div className="space-y-6">
      {/* Title */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3">
        <div>
          <h1 className="text-2xl sm:text-3xl font-extrabold text-slate-900 tracking-tight">
            Prescriptive Recommendations
          </h1>
          <p className="text-xs sm:text-sm text-slate-500 mt-0.5">
            Model-driven agronomic interventions to optimize irrigation, fertility, and climate risk buffers
          </p>
        </div>

        <div className="flex items-center gap-2">
          <span className="text-xs font-bold text-emerald-800 bg-emerald-100 px-3 py-1.5 rounded-xl border border-emerald-300">
            5 Priority Prescriptions
          </span>
        </div>
      </div>

      {/* Mandatory Advisory Notice */}
      <div className="p-4 rounded-2xl bg-amber-50 border border-amber-200 text-amber-900 text-xs flex items-start gap-3 shadow-xs">
        <Info className="w-5 h-5 text-amber-600 shrink-0 mt-0.5" />
        <div className="leading-relaxed">
          <strong>Advisory Disclaimer:</strong> These prescriptions are generated by predictive ML/Quantum mathematical models based on sensor telemetry. They serve as decision-support guidance and should be verified with local certified agronomists and soil testing authorities.
        </div>
      </div>

      {/* Cards List */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-5">
        {recommendations.map((rec) => {
          const isDone = completedMap[rec.id];
          return (
            <motion.div
              key={rec.id}
              whileHover={{ y: -3 }}
              className={`p-6 rounded-3xl border transition-all flex flex-col justify-between ${
                isDone
                  ? 'bg-slate-50 border-slate-200 opacity-60'
                  : 'bg-white border-slate-200/90 shadow-xs hover:shadow-md hover:border-emerald-300'
              }`}
            >
              <div>
                <div className="flex items-center justify-between mb-3">
                  <div className="flex items-center gap-2.5">
                    <span className="text-2xl">{rec.icon}</span>
                    <span className="text-xs font-bold uppercase tracking-wider text-slate-500">
                      {rec.category} Management
                    </span>
                  </div>

                  <span
                    className={`text-[10px] font-extrabold px-2.5 py-1 rounded-full uppercase ${
                      rec.priority === 'High' || rec.priority === 'Alert'
                        ? 'bg-rose-100 text-rose-800'
                        : rec.priority === 'Medium'
                        ? 'bg-amber-100 text-amber-800'
                        : 'bg-emerald-100 text-emerald-800'
                    }`}
                  >
                    {rec.priority} Priority
                  </span>
                </div>

                <h3 className={`text-base font-bold mb-2 ${isDone ? 'line-through text-slate-400' : 'text-slate-900'}`}>
                  {rec.title}
                </h3>

                <p className="text-xs text-slate-600 leading-relaxed mb-4">
                  {rec.details}
                </p>

                <div className="p-2.5 rounded-xl bg-slate-50 border border-slate-100 flex items-center justify-between text-xs">
                  <span className="text-slate-500">Expected Yield Effect:</span>
                  <span className="font-bold text-emerald-700 font-mono">{rec.impact}</span>
                </div>
              </div>

              <div className="mt-5 pt-4 border-t border-slate-100 flex items-center justify-between">
                <button
                  type="button"
                  onClick={() => toggleTask(rec.id)}
                  className="flex items-center gap-2 text-xs font-semibold text-slate-600 hover:text-slate-900 cursor-pointer"
                >
                  {isDone ? (
                    <>
                      <CheckCircle2 className="w-4 h-4 text-emerald-600" />
                      <span className="text-emerald-700 font-bold">Marked as Implemented</span>
                    </>
                  ) : (
                    <>
                      <Circle className="w-4 h-4 text-slate-400" />
                      <span>Mark as Implemented</span>
                    </>
                  )}
                </button>

                <button
                  onClick={() => setActiveTab('what-if')}
                  className="text-xs font-bold text-emerald-600 hover:text-emerald-800 flex items-center gap-1"
                >
                  <span>Simulate in Twin</span>
                  <ArrowRight className="w-3.5 h-3.5" />
                </button>
              </div>
            </motion.div>
          );
        })}
      </div>
    </div>
  );
}
